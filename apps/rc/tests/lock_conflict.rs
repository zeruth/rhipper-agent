//! A merge of main that conflicts in `Cargo.lock` alone is settled before the worker sees it.

use std::path::Path;
use std::process::Command;

fn git(dir: &Path, args: &[&str]) {
    let out = Command::new("git").args(args).current_dir(dir).output().expect("git runs");
    assert!(out.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&out.stderr));
}

fn commit(dir: &Path, subject: &str) {
    git(dir, &["add", "."]);
    git(dir, &["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", subject]);
}

fn lock(version: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"lockdemo\"\nversion = \"{version}\"\n"
    )
}

#[tokio::test]
async fn a_merge_conflicting_only_in_the_lock_is_regenerated_and_concluded() {
    let dir = tempfile::tempdir().expect("a tempdir");
    let root = dir.path();
    git(root, &["init", "-q", "-b", "main"]);
    std::fs::create_dir_all(root.join("src")).unwrap();
    std::fs::write(root.join("Cargo.toml"), "[package]\nname = \"lockdemo\"\nversion = \"0.1.0\"\nedition = \"2021\"\n").unwrap();
    std::fs::write(root.join("src").join("lib.rs"), "").unwrap();
    std::fs::write(root.join("Cargo.lock"), lock("0.1.0")).unwrap();
    commit(root, "base");
    git(root, &["checkout", "-q", "-b", "card"]);
    std::fs::write(root.join("Cargo.lock"), lock("0.3.0")).unwrap();
    commit(root, "card lock");
    git(root, &["checkout", "-q", "main"]);
    std::fs::write(root.join("Cargo.lock"), lock("0.2.0")).unwrap();
    commit(root, "main lock");
    git(root, &["checkout", "-q", "card"]);

    let left = ra_console::agent::merge_main_in(root, "main").await;
    assert_eq!(left, None, "the lock alone is not the worker's");
    let text = std::fs::read_to_string(root.join("Cargo.lock")).unwrap();
    assert!(!text.contains("<<<<<<<"), "no markers: {text}");
    assert!(text.contains("version = \"0.1.0\""), "regenerated for the manifest: {text}");
    git(root, &["rev-parse", "-q", "--verify", "HEAD^2"]);
}

#[tokio::test]
async fn a_conflict_in_another_file_stays_the_workers() {
    let dir = tempfile::tempdir().expect("a tempdir");
    let root = dir.path();
    git(root, &["init", "-q", "-b", "main"]);
    std::fs::write(root.join("a.txt"), "base\n").unwrap();
    commit(root, "base");
    git(root, &["checkout", "-q", "-b", "card"]);
    std::fs::write(root.join("a.txt"), "card\n").unwrap();
    commit(root, "card");
    git(root, &["checkout", "-q", "main"]);
    std::fs::write(root.join("a.txt"), "main\n").unwrap();
    commit(root, "main");
    git(root, &["checkout", "-q", "card"]);

    assert_eq!(ra_console::agent::merge_main_in(root, "main").await, Some(1));
}
